-- Función para contar outfits
local function countOutfits(player)
    local outfits = player:getSex() == 0 and femaleOutfits or maleOutfits
    local count = 0
    for _, looktype in ipairs(outfits) do
        if player:hasOutfit(looktype, 3) then
            count = count + 1
        end
    end
    player:setStorageValue(200200, count)
    return count
end

-- Función para contar monturas
local function countMounts(player)
    local count = 0
    for i = 1, 218 do
        if player:hasMount(i) then
            count = count + 1
        end
    end
    player:setStorageValue(200300, count)
    return count
end

-- Función para mostrar el menú de logros
local function showAchievementsMenu(player)
    local menu = ModalWindow{
        title = "Achievements",
        message = "Choose a section:\n[" .. player:getStorageValue(200000) .. "] Points."
    }

    for _, section in ipairs(config) do
        menu:addChoice(section.articulo, function(player, button, choice)
            if button.name == "Open" then
                local secondMenu = ModalWindow{title = "Achievements", message = "Choose for details"}
                for _, logro in ipairs(section.logros) do
					if section.articulo == "Complete Outfits" then
						selectType = logro.unlock:match("Unlock (.+) Outfits(.+)"):lower()	
						selectTypeNumber = tonumber(selectType)
						text = player:getStorageValue(logro.storage) >= selectTypeNumber and logro.unlock or logro.locked
					elseif section.articulo == "Tamed Mounts" then
						selectType = logro.unlock:match("Unlock (.+) Mounts(.+)"):lower()	
						selectTypeNumber = tonumber(selectType)
						text = player:getStorageValue(logro.storage) >= selectTypeNumber and logro.unlock or logro.locked
					else
						text = player:getStorageValue(logro.storage) == 1 and logro.unlock or logro.locked
					end
                    secondMenu:addChoice(text)
                end
                secondMenu:addButton("Back", function(player)
                    showAchievementsMenu(player)
                end)
                secondMenu:addButton("Close")
                secondMenu:sendToPlayer(player)
            end
        end)
    end

    menu:addButton("Open")
    menu:addButton("Exit")
    menu:sendToPlayer(player)
end

-- Función principal
function logros.onSay(player, words, param)
    countOutfits(player)
    countMounts(player)
    showAchievementsMenu(player)
    return true
end

