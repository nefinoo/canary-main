						local opcion = outfit[y]
							local selectType = opcion.unlock:match("Unlock (.+) Outfits(.+)"):lower()	
							local selectTypeNumber = tonumber(selectType)
							if Outfits >= selectTypeNumber then
								secondMenu:addChoice(string.format("%s", opcion.unlock), function (player, button, choice)end)
